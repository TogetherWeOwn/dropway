import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { authInstance, browser, followed, ORIGIN, type BrowserRequest } from "./auth-submit-helpers.ts";

/**
 * Breaks caught: native no-referrer submit escaping interception; consuming a
 * login token on load; omitting cookies or the form's token; fabricating browser
 * security headers; ignoring a followed redirect; navigating on refusal; and
 * leaving a failed submission unable to retry. The VM executes the unmodified
 * production function against genuine server-rendered forms and issued tokens.
 * Fetch responses/DOM are doubles: this is NOT browser-header or release proof.
 */
let instance: Awaited<ReturnType<typeof authInstance>>;
beforeAll(async () => { instance = await authInstance(); });
afterAll(async () => { await instance?.dispose(); });

const cases = [
  { kind: "login", action: "/login/confirm", destination: "/dashboard/sessions" },
  { kind: "logout", action: "/api/v1/auth/logout", destination: "/login" },
] as const;

for (const { kind, action, destination } of cases) {
  describe(`deliberate ${kind} submission under no-referrer`, () => {
    async function fixture(respond: (request: BrowserRequest) => Promise<Response>) {
      const page = await instance.page(kind);
      const b = browser(page, respond);
      const form = b.document.querySelector(`form[action="${action}"]`);
      expect(form, "exercise the actual server-rendered form, not an invented element").toBeTruthy();
      expect(form!.method.toLowerCase(), "retain the guarded native POST fallback").toBe("post");
      expect(form!.action).toBe(ORIGIN + action);
      if (kind === "login") expect(form!.querySelector('input[name="token"]')?.value).toBe(page.token);
      return { ...b, form: form!, token: page.token };
    }

    async function expectDeliberatePost(b: Awaited<ReturnType<typeof fixture>>, count = 1) {
      const submissions = b.requests.filter((request) => new URL(request.url).pathname === action);
      expect(submissions, "each user submit must produce exactly one first-party fetch POST").toHaveLength(count);
      for (const request of submissions) {
        expect(request.url).toBe(ORIGIN + action);
        expect(request.method).toBe("POST");
        expect(request.credentials, "HttpOnly proof travels through the browser cookie jar").toBe("same-origin");
        for (const [name] of request.headers) {
          expect(name, "Origin/Fetch Metadata must be generated by the browser, never the script").not.toMatch(/^(?:origin|sec-fetch-.*|cookie|authorization)$/i);
        }
        if (kind === "login") {
          const fields = new URLSearchParams(await request.clone().text());
          expect(fields.getAll("token"), "submit the token from the genuine form, not a URL/constant/storage substitute").toEqual([b.token]);
        }
      }
      expect(b.requests.some((request) => new URL(request.url).pathname === "/claim")).toBe(false);
      expect(b.storage.get("dw_pending_claim"), "sign-in/out must not consume a pending site claim").toBe(b.pending);
    }

    it("does not submit, navigate, or claim merely because its page loaded", async () => {
      const b = await fixture(async () => followed(destination));
      // Session-page refresh is a separate, existing contract; it is not logout.
      expect(b.requests.filter((request) => new URL(request.url).pathname !== "/api/v1/auth/sessions/refresh")).toEqual([]);
      expect(b.navigations).toEqual([]);
      expect(b.storage.get("dw_pending_claim")).toBe(b.pending);
    });

    it("intercepts a form submit event, POSTs its controls with cookies, and follows success", async () => {
      const b = await fixture(async () => followed(destination));
      const event = await b.submit(b.form);
      expect(event.defaultPrevented, "native no-referrer submission must not race the first-party fetch").toBe(true);
      await expectDeliberatePost(b);
      expect(b.navigations.map((url) => new URL(url, ORIGIN).href)).toEqual([ORIGIN + destination]);
    });

    it.each([403, 500])("does not navigate or claim on HTTP %i and leaves deliberate retry possible", async (status) => {
      let attempts = 0;
      const b = await fixture(async () => ++attempts === 1
        ? new Response("Submission refused. Retry when allowed.", { status })
        : followed(destination));
      const first = await b.submit(b.form);
      expect(first.defaultPrevented).toBe(true);
      await expectDeliberatePost(b);
      expect(b.navigations).toEqual([]);
      expect(b.document.getElementById("dw-auth-status")?.textContent.trim()).toBeTruthy();
      expect(b.form.querySelector("button")?.disabled).toBe(false);
      const retry = await b.submit(b.form);
      expect(retry.defaultPrevented).toBe(true);
      expect(attempts).toBe(2);
      await expectDeliberatePost(b, 2);
      expect(b.navigations.map((url) => new URL(url, ORIGIN).href)).toEqual([ORIGIN + destination]);
    });

    it("handles a network rejection without navigation and permits another submit", async () => {
      let attempts = 0;
      const b = await fixture(async () => {
        if (++attempts === 1) throw new TypeError("Network unavailable");
        return followed(destination);
      });
      const first = await b.submit(b.form);
      expect(first.defaultPrevented).toBe(true);
      await expectDeliberatePost(b);
      expect(b.navigations).toEqual([]);
      expect(b.document.getElementById("dw-auth-status")?.textContent.trim()).toBeTruthy();
      expect(b.form.querySelector("button")?.disabled).toBe(false);
      await b.submit(b.form);
      expect(attempts).toBe(2);
      await expectDeliberatePost(b, 2);
      expect(b.navigations.map((url) => new URL(url, ORIGIN).href)).toEqual([ORIGIN + destination]);
    });
  });
}

// Positive control for the harness, not a product claim/release test: the
// existing claim interception exercises the same DOM event and serialization.
it("can execute existing claim interception against its genuine form", async () => {
  const b = browser(await instance.page("claim"), async () => followed("/dashboard/sessions?claimed=submit-control"));
  const form = b.document.getElementById("dw-claim");
  expect(form).toBeTruthy();
  form!.querySelector('input[name="claimToken"]')!.value = "serialization-control & +";
  expect((await b.submit(form!)).defaultPrevented).toBe(true);
  const request = b.requests.find((entry) => new URL(entry.url).pathname === "/claim");
  expect(request?.credentials).toBe("same-origin");
  expect([...new URLSearchParams(await request!.text())]).toEqual([
    ["slug", "submit-control"], ["claimToken", "serialization-control & +"],
  ]);
  expect(b.navigations).toEqual([ORIGIN + "/dashboard/sessions?claimed=submit-control"]);
});

it("navigates to sign-in after the existing JSON logout success response", async () => {
  const b = browser(await instance.page("logout"), async () => Response.json({ signedOut: true }));
  const form = b.document.querySelector('form[action="/api/v1/auth/logout"]');
  expect(form).toBeTruthy();
  expect((await b.submit(form!)).defaultPrevented).toBe(true);
  expect(b.requests.filter((request) => new URL(request.url).pathname === "/api/v1/auth/logout")).toHaveLength(1);
  expect(b.navigations.map((url) => new URL(url, ORIGIN).href)).toEqual([ORIGIN + "/login"]);
});
