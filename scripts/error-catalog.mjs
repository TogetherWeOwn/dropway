import { build } from "esbuild";

const bundle = await build({
  stdin: { contents: 'export { ERROR_CODES } from "./packages/core/src/error-codes.ts";', resolveDir: process.cwd(), loader: "ts" },
  bundle: true, write: false, platform: "node", format: "esm", logLevel: "warning",
});
const { ERROR_CODES } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString("base64")}`);

console.log("# Delivery errors\n\nGenerated by `node scripts/error-catalog.mjs` from the core error catalog. Existing non-delivery errors retain their documented behavior.\n");
console.log("| Code | HTTP | Retryable | Hint |\n|---|---|---|---|");
for (const [code, value] of Object.entries(ERROR_CODES)) {
  console.log(`| \`${code}\` | ${value.status} | ${value.retryable} | ${value.hint} |`);
}
console.log("\nUnlock throttles use the shared `rate_limited` (429) code with `Retry-After`. Invalid operation shapes use `invalid_request` (400); permanent slug reservations use `slug_taken` (409). A takedown response never includes its private reason.");
